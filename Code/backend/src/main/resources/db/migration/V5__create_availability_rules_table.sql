-- V5: availability_rules (ERD "AVAILABILITY_RULES"). PK/reference ids are BIGINT (team decision D1).
-- day_of_week is ISO-8601: 1 = Monday ... 7 = Sunday (java.time.DayOfWeek#getValue).
-- start_time/end_time are wall-clock times in users.timezone (E3); a window fits within one day,
-- start_time < end_time, and 24:00 is not allowed. The ERD has created_at only (no updated_at, D9).
-- Overlapping rules are allowed; expansion (AV-04) merges them.
-- Never edit this file once applied; add a new V<n>__*.sql migration instead.

CREATE TABLE availability_rules (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id      BIGINT                   NOT NULL,
    day_of_week  SMALLINT                 NOT NULL,
    start_time   TIME                     NOT NULL,
    end_time     TIME                     NOT NULL,
    is_active    BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_availability_rules PRIMARY KEY (id),
    CONSTRAINT fk_availability_rules_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_availability_rules_day_of_week CHECK (day_of_week BETWEEN 1 AND 7),
    -- 24:00 is the largest TIME value, so end_time <> 24:00 together with start_time < end_time also excludes start_time = 24:00.
    CONSTRAINT ck_availability_rules_time_range CHECK (
        start_time < end_time AND end_time <> TIME '24:00:00')
);

CREATE INDEX idx_availability_rules_user_day ON availability_rules (user_id, day_of_week);
