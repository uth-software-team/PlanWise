-- V1: users table (ERD "USERS"). PK is BIGINT identity (team decision 2026-11-17).
-- Never edit this file once applied; add a new V<n>__*.sql migration instead.

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email          VARCHAR(255)             NOT NULL,
    password_hash  VARCHAR(255)             NOT NULL,
    full_name      VARCHAR(100)             NOT NULL,
    timezone       VARCHAR(50)              NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
    planning_start TIME                     NOT NULL DEFAULT TIME '08:00',
    planning_end   TIME                     NOT NULL DEFAULT TIME '18:00',
    is_active      BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_users PRIMARY KEY (id),
    -- Service layer stores email trimmed + lower-cased, so a plain unique key is enough.
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_email_not_blank CHECK (length(trim(email)) > 0),
    CONSTRAINT ck_users_full_name_not_blank CHECK (length(trim(full_name)) > 0),
    CONSTRAINT ck_users_planning_window CHECK (planning_start < planning_end)
);
