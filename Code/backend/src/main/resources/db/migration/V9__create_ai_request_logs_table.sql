-- V9: ai_request_logs (ERD "AI_REQUEST_LOGS"). PK/reference ids are BIGINT (team decision D1).
-- Stores metadata only (prompt_hash), never the prompt text (CG-08).
-- Deviation from the ERD (explicit TV1 decision 2026-11-19): tokens_used is nullable.
-- 0 = known zero usage, including a fake client that makes no provider call;
-- NULL = provider usage unknown (e.g. timeout or a provider response without usage data).
-- MVP request type is TASK_PARSE. Successful requests have a NULL error_code; failed ones have a code
-- (provider, timeout and invalid provider JSON failures are logged as AI_UNAVAILABLE). error_code is VARCHAR(64) NULL as in the ERD.
-- Never edit this file once applied; add a new V<n>__*.sql migration instead.

CREATE TABLE ai_request_logs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id       BIGINT                   NOT NULL,
    request_type  VARCHAR(32)              NOT NULL,
    prompt_hash   VARCHAR(64)              NOT NULL,
    tokens_used   INT,
    latency_ms    INT                      NOT NULL,
    success       BOOLEAN                  NOT NULL,
    error_code    VARCHAR(64),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_ai_request_logs PRIMARY KEY (id),
    CONSTRAINT fk_ai_request_logs_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_ai_request_logs_request_type CHECK (request_type IN ('TASK_PARSE')),
    CONSTRAINT ck_ai_request_logs_tokens_used CHECK (tokens_used IS NULL OR tokens_used >= 0),
    CONSTRAINT ck_ai_request_logs_latency CHECK (latency_ms >= 0),
    CONSTRAINT ck_ai_request_logs_outcome CHECK (
        (success AND error_code IS NULL) OR (NOT success AND error_code IS NOT NULL))
);

-- A user's recent AI requests.
CREATE INDEX idx_ai_request_logs_user_created ON ai_request_logs (user_id, created_at DESC);
