-- V10: schedule_proposals + schedule_sessions (ERD "SCHEDULE_PROPOSALS", "SCHEDULE_SESSIONS"). PK/reference ids are
-- BIGINT (team decision D1; the class diagram's UUID batch id is replaced by the BIGINT id).
-- Proposal status is PROPOSED/CONFIRMED/CANCELLED and source is ENGINE/AI (TV1 decision 2026-11-19, SC-01).
-- A batch replaced by a new generate, or discarded by the user, becomes CANCELLED; confirmed_at is set only on CONFIRMED.
-- Every edit/delete/confirm checks and increments the batch version (optimistic locking, 409 STALE_VERSION);
-- the session version is informational. Hard constraints HC-01..HC-09 (overlap, availability, deadline...) are checked
-- in the service (SC-04/SC-07), not by the database. Intervals are half-open [start_at, end_at).
-- rest_blocks is cut from the MVP (team decision D2), so no table references schedule_sessions yet.
-- Never edit this file once applied; add a new V<n>__*.sql migration instead.

CREATE TABLE schedule_proposals (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id        BIGINT                   NOT NULL,
    week_start     DATE                     NOT NULL,
    horizon_start  TIMESTAMP WITH TIME ZONE NOT NULL,
    horizon_end    TIMESTAMP WITH TIME ZONE NOT NULL,
    source         VARCHAR(12)              NOT NULL,
    status         VARCHAR(16)              NOT NULL DEFAULT 'PROPOSED',
    version        INT                      NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at   TIMESTAMP WITH TIME ZONE,

    CONSTRAINT pk_schedule_proposals PRIMARY KEY (id),
    CONSTRAINT fk_schedule_proposals_user FOREIGN KEY (user_id) REFERENCES users (id),
    -- ERD UNIQUE (ProposalID, UserID): target of the composite foreign key from schedule_sessions.
    CONSTRAINT uk_schedule_proposals_id_user UNIQUE (id, user_id),
    CONSTRAINT ck_schedule_proposals_source CHECK (source IN ('ENGINE', 'AI')),
    CONSTRAINT ck_schedule_proposals_status CHECK (status IN ('PROPOSED', 'CONFIRMED', 'CANCELLED')),
    CONSTRAINT ck_schedule_proposals_horizon CHECK (horizon_start < horizon_end),
    -- CONFIRMED has a confirmation time; PROPOSED/CANCELLED have none.
    -- Written as implications so an unknown status only violates ck_schedule_proposals_status.
    CONSTRAINT ck_schedule_proposals_confirmed_at CHECK (
        (status <> 'CONFIRMED' OR confirmed_at IS NOT NULL)
        AND (status NOT IN ('PROPOSED', 'CANCELLED') OR confirmed_at IS NULL))
);

-- At most one active PROPOSED batch per user (design doc package 4; team addition, not drawn in the ERD).
CREATE UNIQUE INDEX uk_schedule_proposals_active_user
    ON schedule_proposals (user_id) WHERE status = 'PROPOSED';

CREATE TABLE schedule_sessions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    proposal_id  BIGINT                   NOT NULL,
    task_id      BIGINT                   NOT NULL,
    user_id      BIGINT                   NOT NULL,
    start_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    status       VARCHAR(16)              NOT NULL DEFAULT 'PROPOSED',
    version      INT                      NOT NULL DEFAULT 0,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_schedule_sessions PRIMARY KEY (id),
    -- ERD FK (ProposalID, UserID) -> PROPOSALS: a session always belongs to its proposal's owner.
    -- Both columns are NOT NULL, so MATCH SIMPLE can never skip the check.
    CONSTRAINT fk_schedule_sessions_proposal_user FOREIGN KEY (proposal_id, user_id)
        REFERENCES schedule_proposals (id, user_id),
    CONSTRAINT fk_schedule_sessions_task FOREIGN KEY (task_id) REFERENCES tasks (id),
    CONSTRAINT fk_schedule_sessions_user FOREIGN KEY (user_id) REFERENCES users (id),
    -- ERD UNIQUE (SessionID, ProposalID, UserID): kept for ERD fidelity; it was the target of the rest_blocks
    -- composite foreign key, and rest_blocks is cut from the MVP (D2).
    CONSTRAINT uk_schedule_sessions_id_proposal_user UNIQUE (id, proposal_id, user_id),
    CONSTRAINT ck_schedule_sessions_status CHECK (status IN ('PROPOSED', 'CONFIRMED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_schedule_sessions_time_range CHECK (start_at < end_at)
);

-- Busy/calendar range queries per user.
CREATE INDEX idx_schedule_sessions_user_start ON schedule_sessions (user_id, start_at);
-- Sessions of a batch (the composite FK and uk_schedule_sessions_id_proposal_user do not lead with proposal_id).
CREATE INDEX idx_schedule_sessions_proposal ON schedule_sessions (proposal_id);
CREATE INDEX idx_schedule_sessions_task ON schedule_sessions (task_id);
