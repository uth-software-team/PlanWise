-- V7: team_groups + group_members (ERD "TEAM_GROUPS", "GROUP_MEMBERS"). PK/reference ids are BIGINT (team decision D1).
-- Membership status is ACTIVE/INACTIVE (TV1 decision 2026-11-19): a user who rejoins reactivates the same row
-- (left_at cleared, joined_at reset, role assigned for that admission); a former LEADER role is never restored implicitly.
-- Also adds the deferred foreign key tasks.group_id -> team_groups (tasks is created in V4, CG-03).
-- Not blank = contains at least one non-whitespace character ('[^[:space:]]'; trim() would only strip spaces).
-- Never edit this file once applied; add a new V<n>__*.sql migration instead.

CREATE TABLE team_groups (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_by_user_id  BIGINT                   NOT NULL,
    group_name          VARCHAR(100)             NOT NULL,
    description         TEXT                     NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_team_groups PRIMARY KEY (id),
    CONSTRAINT fk_team_groups_created_by_user FOREIGN KEY (created_by_user_id) REFERENCES users (id),
    CONSTRAINT ck_team_groups_group_name_not_blank CHECK (group_name ~ '[^[:space:]]')
);

CREATE TABLE group_members (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    group_id   BIGINT                   NOT NULL,
    user_id    BIGINT                   NOT NULL,
    role       VARCHAR(16)              NOT NULL,
    status     VARCHAR(16)              NOT NULL DEFAULT 'ACTIVE',
    joined_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    left_at    TIMESTAMP WITH TIME ZONE,

    CONSTRAINT pk_group_members PRIMARY KEY (id),
    CONSTRAINT fk_group_members_group FOREIGN KEY (group_id) REFERENCES team_groups (id),
    CONSTRAINT fk_group_members_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_group_members_group_user UNIQUE (group_id, user_id),
    CONSTRAINT ck_group_members_role CHECK (role IN ('LEADER', 'MEMBER')),
    CONSTRAINT ck_group_members_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    -- Written as implications so an unknown status only violates ck_group_members_status.
    CONSTRAINT ck_group_members_left_at CHECK (
        (status <> 'ACTIVE' OR left_at IS NULL) AND (status <> 'INACTIVE' OR left_at IS NOT NULL)),
    CONSTRAINT ck_group_members_left_after_join CHECK (left_at IS NULL OR left_at >= joined_at)
);

-- "My groups" lookups; uk_group_members_group_user already covers lookups by group_id.
CREATE INDEX idx_group_members_user ON group_members (user_id);

-- tasks.group_id was created in V4 without a foreign key because team_groups did not exist yet (CG-03).
-- idx_tasks_group from V4 already indexes the column. No ON DELETE: deleting a group never deletes its tasks.
ALTER TABLE tasks
    ADD CONSTRAINT fk_tasks_group FOREIGN KEY (group_id) REFERENCES team_groups (id);
