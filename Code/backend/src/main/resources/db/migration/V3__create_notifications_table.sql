-- V3: notifications (ERD "NOTIFICATIONS"). PK/reference ids are BIGINT (team decision D1).
-- reference_id points to different tables depending on reference_type, so it has no foreign key.
-- type values mirror modules/notification/api/NotificationType.
-- Never edit this file once applied; add a new V<n>__*.sql migration instead.

CREATE TABLE notifications (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT                   NOT NULL,
    type            VARCHAR(40)              NOT NULL,
    title           VARCHAR(255)             NOT NULL,
    content         TEXT,
    reference_type  VARCHAR(24),
    reference_id    BIGINT,
    is_read         BOOLEAN                  NOT NULL DEFAULT FALSE,
    read_at         TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_notifications PRIMARY KEY (id),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_notifications_type CHECK (type IN (
        'TASK_ASSIGNED', 'ASSIGNMENT_ACCEPTED', 'ASSIGNMENT_DECLINED', 'ASSIGNMENT_REVOKED',
        'DEADLINE_REMINDER', 'TASK_OVERDUE', 'SCHEDULE_PROPOSAL_READY', 'SCHEDULE_CONFLICT')),
    CONSTRAINT ck_notifications_title_not_blank CHECK (length(trim(title)) > 0),
    CONSTRAINT ck_notifications_read_state CHECK (
        (is_read = FALSE AND read_at IS NULL) OR (is_read = TRUE AND read_at IS NOT NULL))
);

-- List a user's notifications, unread first / newest first.
CREATE INDEX idx_notifications_user_read_created ON notifications (user_id, is_read, created_at DESC);
