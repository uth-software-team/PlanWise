-- V6: fixed_events (ERD "FIXED_EVENTS"). PK/reference ids are BIGINT (team decision D1).
-- recurrence_type is required: ONCE or WEEKLY (ERD CHECK, E2). Unused recurrence columns stay nullable
-- (the service rejects fields of the other type, AV-03).
-- ONCE: start_at/end_at required (TIMESTAMPTZ, may cross midnight).
-- WEEKLY: day_of_week (ISO 1 = Monday ... 7 = Sunday), start_time, end_time required; one day, no 24:00.
-- Any supplied value is validated; any supplied pair must be ordered start < end.
-- effective_from/effective_until are optional DATE bounds, ordered when both are set.
-- Recurrence CHECKs are written as implications so an unknown recurrence_type only violates ck_fixed_events_recurrence_type.
-- Never edit this file once applied; add a new V<n>__*.sql migration instead.

CREATE TABLE fixed_events (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id          BIGINT                   NOT NULL,
    title            VARCHAR(255)             NOT NULL,
    note             TEXT,
    recurrence_type  VARCHAR(10)              NOT NULL,
    day_of_week      SMALLINT,
    start_time       TIME,
    end_time         TIME,
    start_at         TIMESTAMP WITH TIME ZONE,
    end_at           TIMESTAMP WITH TIME ZONE,
    effective_from   DATE,
    effective_until  DATE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_fixed_events PRIMARY KEY (id),
    CONSTRAINT fk_fixed_events_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_fixed_events_title_not_blank CHECK (title ~ '[^[:space:]]'),
    CONSTRAINT ck_fixed_events_recurrence_type CHECK (recurrence_type IN ('ONCE', 'WEEKLY')),
    CONSTRAINT ck_fixed_events_once CHECK (
        recurrence_type <> 'ONCE' OR (start_at IS NOT NULL AND end_at IS NOT NULL)),
    CONSTRAINT ck_fixed_events_weekly CHECK (
        recurrence_type <> 'WEEKLY'
        OR (day_of_week IS NOT NULL AND start_time IS NOT NULL AND end_time IS NOT NULL)),
    CONSTRAINT ck_fixed_events_day_of_week CHECK (
        day_of_week IS NULL OR day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_fixed_events_time_range CHECK (
        (start_time IS NULL OR start_time <> TIME '24:00:00')
        AND (end_time IS NULL OR end_time <> TIME '24:00:00')
        AND (start_time IS NULL OR end_time IS NULL OR start_time < end_time)),
    CONSTRAINT ck_fixed_events_at_range CHECK (
        start_at IS NULL OR end_at IS NULL OR start_at < end_at),
    CONSTRAINT ck_fixed_events_effective_range CHECK (
        effective_from IS NULL OR effective_until IS NULL OR effective_from <= effective_until)
);

CREATE INDEX idx_fixed_events_user ON fixed_events (user_id);
