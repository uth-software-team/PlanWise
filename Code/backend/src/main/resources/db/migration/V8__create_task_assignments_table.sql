-- V8: task_assignments (ERD "TASK_ASSIGNMENTS"). PK/reference ids are BIGINT (team decision D1).
-- The ERD has no version column: stale transitions are rejected by conditional updates in the service
-- (409 DATA_CONFLICT); an existing PENDING/ACCEPTED assignment is 409 ASSIGNMENT_ALREADY_ACTIVE (BR-04).
-- Accept/decline set responded_at; revoke keeps its previous value, including NULL (TV1 decision 2026-11-19).
-- Never edit this file once applied; add a new V<n>__*.sql migration instead.

CREATE TABLE task_assignments (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    task_id              BIGINT                   NOT NULL,
    assignee_user_id     BIGINT                   NOT NULL,
    assigned_by_user_id  BIGINT                   NOT NULL,
    status               VARCHAR(16)              NOT NULL DEFAULT 'PENDING',
    decline_reason       TEXT,
    responded_at         TIMESTAMP WITH TIME ZONE,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_task_assignments PRIMARY KEY (id),
    CONSTRAINT fk_task_assignments_task FOREIGN KEY (task_id) REFERENCES tasks (id),
    CONSTRAINT fk_task_assignments_assignee FOREIGN KEY (assignee_user_id) REFERENCES users (id),
    CONSTRAINT fk_task_assignments_assigned_by FOREIGN KEY (assigned_by_user_id) REFERENCES users (id),
    CONSTRAINT ck_task_assignments_status CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'REVOKED')),
    -- A DECLINED reason must contain at least one non-whitespace character (spaces, tabs and newlines alone fail).
    -- status is NOT NULL, so "<>" is never NULL; a NULL reason is rejected explicitly before the regex runs.
    CONSTRAINT ck_task_assignments_decline_reason CHECK (
        status <> 'DECLINED' OR (decline_reason IS NOT NULL AND decline_reason ~ '[^[:space:]]')),
    -- PENDING has no response yet; ACCEPTED/DECLINED have one; REVOKED keeps whatever it had (NULL or not).
    -- Written as implications so an unknown status only violates ck_task_assignments_status.
    CONSTRAINT ck_task_assignments_responded_at CHECK (
        (status <> 'PENDING' OR responded_at IS NULL)
        AND (status NOT IN ('ACCEPTED', 'DECLINED') OR responded_at IS NOT NULL))
);

-- BR-04: at most one PENDING or ACCEPTED assignment per task.
CREATE UNIQUE INDEX uk_task_assignments_active_task
    ON task_assignments (task_id) WHERE status IN ('PENDING', 'ACCEPTED');
-- Assignee inbox, optionally filtered by status.
CREATE INDEX idx_task_assignments_assignee_status ON task_assignments (assignee_user_id, status);
-- Assignment history per task (the partial index above only covers active rows).
CREATE INDEX idx_task_assignments_task ON task_assignments (task_id);
