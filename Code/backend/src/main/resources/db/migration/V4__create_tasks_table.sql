-- V4: tasks (ERD "TASKS"). PK/reference ids are BIGINT (team decision D1).
-- group_id is nullable and has no foreign key here: team_groups is created in V7 (CG-03), where GR-01 adds fk_tasks_group.
-- priority/category/status values mirror the doc enums TaskPriority, TaskCategory, TaskStatus.
-- New tasks default to TODO (BR-02). is_overdue is derived and never stored (BR-03); deleted_at = soft delete.
-- Not blank = contains at least one non-whitespace character ('[^[:space:]]'; trim() would only strip spaces).
-- Never edit this file once applied; add a new V<n>__*.sql migration instead.

CREATE TABLE tasks (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    owner_user_id               BIGINT                   NOT NULL,
    group_id                    BIGINT,
    title                       VARCHAR(255)             NOT NULL,
    description                 TEXT                     NOT NULL,
    deadline                    TIMESTAMP WITH TIME ZONE,
    priority                    VARCHAR(16)              NOT NULL,
    category                    VARCHAR(16)              NOT NULL,
    estimated_duration_minutes  INT                      NOT NULL,
    actual_duration_minutes     INT,
    status                      VARCHAR(20)              NOT NULL DEFAULT 'TODO',
    version                     INT                      NOT NULL DEFAULT 0,
    deleted_at                  TIMESTAMP WITH TIME ZONE,
    created_at                  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_tasks PRIMARY KEY (id),
    CONSTRAINT fk_tasks_owner_user FOREIGN KEY (owner_user_id) REFERENCES users (id),
    CONSTRAINT ck_tasks_title_not_blank CHECK (title ~ '[^[:space:]]'),
    CONSTRAINT ck_tasks_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    CONSTRAINT ck_tasks_category CHECK (category IN ('STUDY', 'WORK', 'PERSONAL', 'PROJECT', 'OTHER')),
    CONSTRAINT ck_tasks_status CHECK (status IN ('TODO', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_tasks_estimated_duration_positive CHECK (estimated_duration_minutes > 0),
    CONSTRAINT ck_tasks_actual_duration_non_negative CHECK (actual_duration_minutes IS NULL OR actual_duration_minutes >= 0)
);

CREATE INDEX idx_tasks_owner_user ON tasks (owner_user_id);
CREATE INDEX idx_tasks_group ON tasks (group_id);
